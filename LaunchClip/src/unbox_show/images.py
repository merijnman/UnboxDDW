"""Artwork stage: generate the images listed under `artwork:` that are missing.

Generated files land in assets/screens/ next to artwork supplied by the team.
assets/screens/generated.json records which files were generated and from
which prompt. A file is only (re)generated when it is missing, or when it was
generated by us, is unchanged since, and its prompt changed. Anything a person
put there wins.
"""

from __future__ import annotations

import hashlib
import io
import json
from dataclasses import dataclass, field
from pathlib import Path

from . import cache as cache_mod
from .cache import Cache, write_bytes_atomic
from .eleven import Client
from .model import ShowFile

MANIFEST = "generated.json"


def _as_png(data: bytes) -> bytes:
    """The API may answer with JPEG or WebP; our files are PNG."""
    from PIL import Image

    out = io.BytesIO()
    Image.open(io.BytesIO(data)).convert("RGB").save(out, "PNG")
    return out.getvalue()


@dataclass
class ImageStats:
    generated: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)


def screens_dir(show: ShowFile) -> Path:
    return show.base_dir / "assets" / "screens"


def image_key(show: ShowFile, name: str, take: int = 0) -> str:
    art = show.artwork
    data = {
        "model_id": art.model_id,
        "prompt": art.full_prompt(name),
        "aspect_ratio": art.images[name].aspect_ratio,
        "resolution": art.resolution,
    }
    if take:
        data["take"] = take
    return cache_mod.key(data)


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_manifest(show: ShowFile) -> dict:
    path = screens_dir(show) / MANIFEST
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def todo(show: ShowFile, reroll: set[str] = frozenset()) -> list[str]:
    """Names that would be generated (and cost credits)."""
    if not show.artwork:
        return []
    folder = screens_dir(show)
    manifest = load_manifest(show)
    names = []
    for name in show.artwork.images:
        path = folder / name
        record = manifest.get(name)
        if name in reroll:
            names.append(name)
        elif not path.exists():
            names.append(name)
        elif record and record["sha256"] == _sha(path) and record["key"] != image_key(show, name, record.get("take", 0)):
            names.append(name)  # ours, untouched, and the prompt changed
    return names


def render(show: ShowFile, client: Client, cache: Cache, reroll: set[str] = frozenset()) -> ImageStats:
    stats = ImageStats()
    folder = screens_dir(show)
    manifest = load_manifest(show)
    pending = todo(show, reroll)
    for name in show.artwork.images if show.artwork else {}:
        if name not in pending:
            stats.kept.append(name)
            continue
        take = manifest.get(name, {}).get("take", 0) + (1 if name in reroll else 0)
        digest = image_key(show, name, take)
        cached = cache.get("img", digest, "png")
        if cached is None:
            spec = show.artwork.images[name]
            data = client.image(show.artwork.full_prompt(name), show.artwork.model_id, spec.aspect_ratio,
                                show.artwork.resolution)
            cached = cache.put("img", digest, "png", _as_png(data))
        target = folder / name
        write_bytes_atomic(target, cached.read_bytes())
        manifest[name] = {"key": digest, "take": take, "sha256": _sha(target)}
        stats.generated.append(name)
    if stats.generated:
        text = json.dumps(dict(sorted(manifest.items())), indent=2) + "\n"
        write_bytes_atomic(folder / MANIFEST, text.encode("utf-8"))
    return stats
